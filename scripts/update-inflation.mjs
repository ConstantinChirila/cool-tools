// Refreshes lib/inflation-data.ts from the ONS consumer price inflation dataset (MM23).
// Run with `pnpm data:inflation`, check the diff, then bump the inflation entry in
// scripts/data-reviews.json.

import { writeFile } from "node:fs/promises";

const BASE = "https://www.ons.gov.uk/economy/inflationandpriceindices/timeseries";
const OUT = new URL("../lib/inflation-data.ts", import.meta.url);

async function series(cdid) {
  const res = await fetch(`${BASE}/${cdid}/mm23/data`, { headers: { "User-Agent": "bitsnbobs.tools data refresh" } });
  if (!res.ok) throw new Error(`${cdid}: HTTP ${res.status}`);
  return res.json();
}

/** Annual averages, then the latest month standing in for a year that is not finished yet. */
function annual(json) {
  const years = json.years.map((y) => ({ year: Number(y.date), value: Number(y.value) }));
  const last = json.months.at(-1);
  const [year, month] = last.date.split(" ");
  const partial = Number(year) > years.at(-1).year;
  if (partial) years.push({ year: Number(year), value: Number(last.value) });
  for (let i = 1; i < years.length; i++) {
    if (years[i].year !== years[i - 1].year + 1) throw new Error(`${json.description.cdid}: gap after ${years[i - 1].year}`);
  }
  return { first: years[0].year, values: years.map((y) => y.value), latest: { year: Number(year), month, partial } };
}

const [cpiJson, rpiJson, cpiRateJson, rpiRateJson] = await Promise.all(["d7bt", "cdko", "d7g7", "czbh"].map(series));
const cpi = annual(cpiJson);
const rpi = annual(rpiJson);
if (cpi.latest.year !== rpi.latest.year || cpi.latest.month !== rpi.latest.month) {
  throw new Error(`CPI runs to ${cpi.latest.month} ${cpi.latest.year} but RPI to ${rpi.latest.month} ${rpi.latest.year}`);
}
const monthName = (m) => m.charAt(0) + m.slice(1).toLowerCase();
const released = new Intl.DateTimeFormat("en-CA", { timeZone: "Europe/London" }).format(new Date(cpiJson.description.releaseDate));

const data = {
  released,
  nextRelease: cpiJson.description.nextRelease,
  latest: {
    year: cpi.latest.year,
    month: monthName(cpi.latest.month),
    partial: cpi.latest.partial,
    cpiRate: Number(cpiRateJson.months.at(-1).value),
    rpiRate: Number(rpiRateJson.months.at(-1).value),
  },
  cpi: { first: cpi.first, values: cpi.values },
  rpi: { first: rpi.first, values: rpi.values },
};

/** Ten values a line, so a refresh diff shows which years moved. */
function numbers(values) {
  const lines = [];
  for (let i = 0; i < values.length; i += 10) lines.push(`      ${values.slice(i, i + 10).join(", ")},`);
  return `\n${lines.join("\n")}\n    `;
}
const object = (o) => `{ ${Object.entries(o).map(([k, v]) => `${k}: ${JSON.stringify(v)}`).join(", ")} }`;
const file = `// Generated by scripts/update-inflation.mjs from ONS series D7BT (CPI, 2015=100),
// CDKO (RPI long-run series, Jan 1974=100), D7G7 and CZBH (12-month rates).
// Do not edit by hand: run \`pnpm data:inflation\`.

export const INFLATION_DATA = {
  /** ONS release the figures come from (UK date). */
  released: "${data.released}",
  nextRelease: "${data.nextRelease}",
  /** Latest month published. When \`partial\`, the last value of each series is that month, not a full-year average. */
  latest: ${object(data.latest)},
  /** Annual average index from \`first\`, one value per year. */
  cpi: {
    first: ${data.cpi.first},
    values: [${numbers(data.cpi.values)}],
  },
  rpi: {
    first: ${data.rpi.first},
    values: [${numbers(data.rpi.values)}],
  },
} as const;
`;

await writeFile(OUT, file);
console.log(`Wrote ${OUT.pathname}: CPI ${data.cpi.first}-${data.latest.year}, RPI ${data.rpi.first}-${data.latest.year}, latest ${data.latest.month} ${data.latest.year} (CPI ${data.latest.cpiRate}%, RPI ${data.latest.rpiRate}%), released ${data.released}.`);
